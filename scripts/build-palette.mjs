/**
 * Writes src/styles/palette.css from the active preset.
 *
 * The scene and the stylesheet have to agree on colour, and keeping two hand
 * edited copies in step is a standing invitation to drift. Generating one from
 * the other removes the possibility.
 *
 * One block: the site is dark, full stop. A light theme was generated here for
 * a day and withdrawn — see the note beside `LIGHT` in engine/palette.js for
 * why, which is about the artwork rather than about the colours. `block()`
 * takes its colours as an argument so that turning it back on is one line, not
 * a rewrite.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { palette, ACTIVE } from '../src/engine/palette.js';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '../src/styles/palette.css');

const rgb = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};

/** One theme's worth of custom properties, from one set of base colours. */
function block(selector, colours, { lineAlpha, tintAlpha }) {
  const [pr, pg, pb] = rgb(colours.primary);
  const [ir, ig, ib] = rgb(colours.ink);
  const [sr, sg, sb] = rgb(colours.smoke);

  return `${selector} {
  --ink: ${colours.ink};
  --paper: ${colours.paper};
  --teal: ${colours.primary};
  --gold: ${colours.accent};
  --muted: ${colours.muted};
  --dim: ${colours.dim};
  --raised: ${colours.raised};
  --line: rgba(${pr}, ${pg}, ${pb}, ${lineAlpha});
  --tint: rgba(${pr}, ${pg}, ${pb}, ${tintAlpha});
  --scrim-rgb: ${ir}, ${ig}, ${ib};
  --wash-rgb: ${sr}, ${sg}, ${sb};
  --veil: rgba(${ir}, ${ig}, ${ib}, 0.88);
  --veil-mid: rgba(${ir}, ${ig}, ${ib}, 0.55);
  --veil-soft: rgba(${ir}, ${ig}, ${ib}, 0);
}`;
}

const css = `/* Generated by scripts/build-palette.mjs — do not edit. Preset: ${ACTIVE}. */
${block(':root', palette, { lineAlpha: 0.18, tintAlpha: 0.06 })}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, css);
console.log(`palette.css written (${ACTIVE})`);
