/**
 * Writes src/styles/palette.css from the active preset.
 *
 * The scene and the stylesheet have to agree on colour, and keeping two hand
 * edited copies in step is a standing invitation to drift. Generating one from
 * the other removes the possibility.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { palette, ACTIVE } from '../src/engine/palette.js';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '../src/styles/palette.css');

const rgb = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};

const [pr, pg, pb] = rgb(palette.primary);
const [ir, ig, ib] = rgb(palette.ink);
const [sr, sg, sb] = rgb(palette.smoke);

const css = `/* Generated by scripts/build-palette.mjs — do not edit. Preset: ${ACTIVE}. */
:root {
  --ink: ${palette.ink};
  --paper: ${palette.paper};
  --teal: ${palette.primary};
  --gold: ${palette.accent};
  --muted: ${palette.muted};
  --dim: ${palette.dim};
  --raised: ${palette.raised};
  --line: rgba(${pr}, ${pg}, ${pb}, 0.18);
  --tint: rgba(${pr}, ${pg}, ${pb}, 0.06);
  --scrim-rgb: ${ir}, ${ig}, ${ib};
  --wash-rgb: ${sr}, ${sg}, ${sb};
  --veil: rgba(${ir}, ${ig}, ${ib}, 0.88);
  --veil-mid: rgba(${ir}, ${ig}, ${ib}, 0.55);
  --veil-soft: rgba(${ir}, ${ig}, ${ib}, 0);
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, css);
console.log(`palette.css written (${ACTIVE})`);
